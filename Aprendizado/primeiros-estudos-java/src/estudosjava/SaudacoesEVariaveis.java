package estudosjava;

/**
 * Exercício de variáveis, tipos de dados e impressão de mensagens.
 */
public class SaudacoesEVariaveis {

    public static void main(String[] args) {
        int salario = 67;
        double altura = 1.70;
        float peso = 55.5f;
        String nome = "Gabriel";
        char sexo = 'n';

        System.out.println("Bom dia, " + nome + "!");
        System.out.println("Salário: " + salario);
        System.out.println("Altura: " + altura);
        System.out.println("Peso: " + peso);
        System.out.println("Caractere informado: " + sexo);
    }
}
